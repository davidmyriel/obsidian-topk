import esbuild from 'esbuild';
import process from 'process';
import { builtinModules } from 'node:module';

// No URLs here: scripts/check-bundle.ts allows only TopK hosts in main.js.
const banner = `/*!
TopK Visual Search. Copyright (c) 2026 TopK. MIT License: see LICENSE in the source repository.
Bundles @bufbuild/protobuf 2.16.0 (Apache-2.0 AND BSD-3-Clause) and code generated from TopK's
protocol definitions (MIT, Copyright (c) 2025 FAFO LABS). See THIRD_PARTY_NOTICES.md.
This file is generated by esbuild from the plugin's TypeScript sources.
*/
`;

const prod = process.argv[2] === 'production';

const context = await esbuild.context({
	banner: {
		js: banner,
	},
	entryPoints: ['src/main.ts'],
	bundle: true,
	external: [
		'obsidian',
		'electron',
		'@codemirror/autocomplete',
		'@codemirror/collab',
		'@codemirror/commands',
		'@codemirror/language',
		'@codemirror/lint',
		'@codemirror/search',
		'@codemirror/state',
		'@codemirror/view',
		'@lezer/common',
		'@lezer/highlight',
		'@lezer/lr',
		...builtinModules,
	],
	format: 'cjs',
	target: 'es2021',
	logLevel: 'info',
	sourcemap: prod ? false : 'inline',
	treeShaking: true,
	outfile: 'main.js',
	minify: prod,
});

if (prod) {
	await context.rebuild();
	process.exit(0);
} else {
	await context.watch();
}
